// The stored last frame check.mjs draws: basic-xlarge-8p, eight seats, a thousand turns.
//
//     node make-last-frame.mjs                  # play the match, then decode its last frame
//     node make-last-frame.mjs --replay FILE    # decode the last frame of a replay you already have
//
// A card on the site rests on the last frame of its match, which the runner decodes once at finish
// and Soma keeps (`GET /v1/matches/{id}/frame`). check.mjs proves `drawFrame` draws one without
// calling the component, and it needs a real one to do that with: the largest a match can leave,
// which is the envelope's top board full of eight colonies. So this plays one -- the `tinybrains`
// CLI, the starter's three trained models round the table -- and decodes its last turn through the
// component in ../dist/viz, exactly as the runner does. Never edit the output by hand: a frame that
// no engine produced proves nothing about the frames Soma will serve.
//
// Needs ../build.sh and ./build.sh first, the `tinybrains` binary ($TINYBRAINS, else on the PATH)
// and the starter's models ($STARTER_MODELS, else an ants-starter checkout beside this one). The
// CLI plays against a registry written here that points at ../dist, so the match is played by the
// same component the viewer carries.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dist = resolve(here, "../dist");
const out = join(here, "last-frame-basic-xlarge-8p.json");
const MAP = "basic-xlarge-8p";
const TURNS = 1000;
const SEED = 20260925;

let replayPath = null;
let work = null;
const at = process.argv.indexOf("--replay");
if (at > 0) replayPath = resolve(process.argv[at + 1]);

if (!replayPath) {
  const models = resolve(process.env.STARTER_MODELS ?? join(here, "../../ants-starter/models"));
  const names = ["nano-bc", "micro-bc", "micro-percell"];
  work = mkdtempSync(join(tmpdir(), "tb-last-frame-"));
  writeFileSync(join(work, "registry.toml"), `[games.ants]\nname = "Ants"\npath = ${JSON.stringify(dist)}\n`);
  const seats = Array.from({ length: 8 }, (_, seat) => {
    const m = names[seat % names.length];
    return { seat, weights: join(models, m, "model.onnx"), manifest: join(models, m, "manifest.json"), label: m };
  });
  const match = {
    game: "ants",
    vars: { max_turns: TURNS },
    rows: [{ id: "last-frame", seed: SEED, map: MAP, seat_count: 8, seats }],
  };
  writeFileSync(join(work, "match.json"), JSON.stringify(match, null, 1));
  console.log(`==> playing ${MAP}, ${TURNS} turns, eight seats (a minute or two)`);
  execFileSync(process.env.TINYBRAINS ?? "tinybrains", [join(work, "match.json"), "--out", join(work, "out")], {
    stdio: "inherit",
    env: { ...process.env, TINYBRAINS_REGISTRY: join(work, "registry.toml") },
  });
  const file = readdirSync(join(work, "out")).find((n) => n.endsWith(".json"));
  replayPath = join(work, "out", file);
}

// The component the viewer carries, as the runner calls it: one frame, at the match's last turn.
const { frameAt } = await import("../dist/viz/engine.js");
const replay = JSON.parse(readFileSync(replayPath, "utf8"));
const turn = Number(replay.turns);
const frame = frameAt(replay, turn);
const engine = JSON.parse(readFileSync(join(dist, "viz/engine.json"), "utf8")).engine_digest;

// The frame route's shape: `{ id, map, turn, seats, frame }`.
const fixture = {
  note: "Generated by make-last-frame.mjs; never edited by hand. The last frame of a match, as tb.ants.replay-decode answers it and Soma serves it.",
  engine_digest: engine,
  id: "fixture",
  map: replay.map?.id ?? MAP,
  turn: frame.turn,
  seats: (replay.seats ?? []).map((s) => ({ seat: s.seat, name: s.label ?? `seat ${s.seat}` })),
  frame,
};
const text = JSON.stringify(fixture);
writeFileSync(out, `${text}\n`);
if (work) rmSync(work, { recursive: true, force: true });
console.log(
  `==> ${out}\n    ${fixture.map}, turn ${frame.turn}, ${frame.score.length} seats, ${frame.ants.length} ants, ` +
    `${(text.length / 1024).toFixed(1)} KB`
);
